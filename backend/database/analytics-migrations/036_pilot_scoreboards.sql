-- ============================================================================
-- 036_pilot_scoreboards.sql - two scoreboards for five stores, kept apart, and
--                             the invoice as a named source of what was bought
-- ============================================================================
-- DATABASE: bottleai_analytics  (applied by database/migrate.js - see 001.)
--
-- WHY
--
-- 1. THE PILOT HAD NO SCOREBOARD IT COULD HAND SOMEBODY.
--
--    The pre-pilot checklist's test paragraph asks for one thing: "Five GOOD
--    stores only. Two scoreboards kept separate: prediction accuracy (needs no
--    owner action) and holdout money (shown vs withheld, action inferred from
--    stock jumps and invoices). Report monthly per store, one line per
--    product." Every figure on it already existed somewhere - lift on the
--    outcome row, the arm on the outcome row, margin on the evaluation row, the
--    holdout comparison in holdoutReport - and nothing assembled them per store
--    per month, so the pilot's result was a query somebody had to write on the
--    day they were asked.
--
--    The two boards are two COLUMNS, not one, because they answer questions
--    that must not be allowed to blur:
--
--      accuracy  did what the card predicted come true - lift, the promise
--                fill ratio, interval coverage, the stockout grade. Both arms
--                count, because a withheld card is still a prediction. Nothing
--                on it reads whether the owner acted, how they voted, or what
--                the margin was: a forecast is graded on the forecast.
--      holdout   did TELLING them change anything - shown against withheld,
--                per product, dollars per product never totals, with the
--                action inferred from the purchases feed, an uploaded invoice,
--                the stock delta or a price drop. This board never headlines a
--                hit rate; that is the other board's figure.
--
--    A reader who sees "85% accurate" next to "+$12 per product" in one row
--    will read the first as the cause of the second. Separate columns, and a
--    page that renders them as separate sections.
--
-- 2. KEYED ON THE MONTH THE WINDOW CLOSED IN.
--
--    `month` is the first day of the calendar month in which a card's 30-day
--    window ENDED - the same convention the offline ledger uses ("windows named
--    by the month they land in"). A card issued on the 25th belongs to next
--    month's board, because that is when its claim could be checked. The
--    30-day window only: it is the first horizon that contains both the 14-day
--    cover and the 7-day lead time the stockout card quotes, and the one the
--    stockout grade is taken on (035).
--
--    One row per (store, month), regenerated by upsert on the first of each
--    month at 07:30 (server.js, PILOT_SCOREBOARD_CRON_SCHEDULE) and by
--    scripts/pilot-scoreboard.js on demand. `data_through` is the latest sales
--    frontier the month's evaluations saw, so a board built before the last
--    windows finalised says so rather than looking complete.
--
--    jsonb rather than columns, deliberately: the board is one line per
--    product and the product list is different every month and every store.
--    The JSON is self-describing - every field is named in plain words, and
--    every null carries its reason under `refusals` - so a row read in a year
--    still explains itself.
--
-- 3. AN INVOICE IS NOW A SOURCE THE OUTCOME ROW MAY NAME.
--
--    035 wrote `purchased_qty_source` with two permitted values: the purchases
--    feed, and the stock inflow. The evaluator now also reads the invoices an
--    owner uploads (purchase_orders / purchase_order_items, 008 and 037) and
--    ranks them between the two - a dated document a person matched outranks
--    an undated inference; a system record outranks a document. The CHECK is
--    widened so the bought quantity can say "invoice". Until this migration is
--    applied the evaluator still proves the ACTION from the invoice (the
--    evidence column is jsonb) and leaves the quantity NULL with the reason,
--    rather than writing the figure under another source's name.
--
-- GRANTS
--
--    SELECT, INSERT, UPDATE: the cron upserts and the route reads. No DELETE -
--    a month's board is regenerated, never erased, and a correction belongs in
--    a migration run by the owner (031 makes the same argument for outcomes).
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS pilot_scoreboards (
  client_id     integer     NOT NULL,
  location_id   integer     NOT NULL,
  -- First day of the calendar month the 30-day windows CLOSED in.
  month         date        NOT NULL,
  generated_at  timestamptz NOT NULL DEFAULT now(),
  -- The latest sales frontier the month's evaluations saw. NULL when the
  -- month had no evaluated card, which the JSON's refusals also say.
  data_through  date,
  -- Board A: prediction accuracy. Reads lift, quantities, the stated range
  -- and the stockout grade; never the arm, the action, the votes or money.
  accuracy      jsonb       NOT NULL,
  -- Board B: holdout money. Shown against withheld per product, dollars per
  -- product, the inferred action and its detector. Never a hit rate.
  holdout       jsonb       NOT NULL,
  PRIMARY KEY (client_id, location_id, month),
  CHECK (month = date_trunc('month', month)::date)
);

COMMENT ON TABLE pilot_scoreboards IS
  'The pilot''s monthly report, one row per store per month, two boards kept '
  'apart: accuracy (needs no owner action) and holdout money (shown vs '
  'withheld). Built by services/pilotScoreboardService.js.';
COMMENT ON COLUMN pilot_scoreboards.month IS
  'First day of the calendar month in which the card''s 30-day window ended - '
  'windows are named by the month they land in, as the offline ledger names '
  'them. A card issued on the 25th is next month''s.';
COMMENT ON COLUMN pilot_scoreboards.data_through IS
  'The latest sales frontier the month''s evaluations had seen when the board '
  'was built. NULL means no evaluated card in the month, not "complete".';

GRANT SELECT, INSERT, UPDATE ON TABLE pilot_scoreboards TO bottleai_writer;

-- ── The invoice as a named source of what was bought ─────────────────────────
-- 035 declared the CHECK inline on the column, so Postgres named it after the
-- table and column. Dropped by that name and re-added with the third value;
-- IF EXISTS so a database that never had 035's inline form is not refused.
ALTER TABLE recommendation_outcomes
  DROP CONSTRAINT IF EXISTS recommendation_outcomes_purchased_qty_source_check;
ALTER TABLE recommendation_outcomes
  ADD CONSTRAINT recommendation_outcomes_purchased_qty_source_check
  CHECK (purchased_qty_source IS NULL
         OR purchased_qty_source IN ('purchases_feed', 'invoice', 'stock_inflow'));

COMMENT ON COLUMN recommendation_outcomes.purchased_qty_source IS
  'Where actual_purchased_qty came from, in order of trust: purchases_feed '
  '(PO rows the POS synced, inside the window), invoice (lines on an uploaded '
  'invoice dated inside the window, matched to the sku by a person), or '
  'stock_inflow (snapshot-to-frontier stock delta plus sales, attributable to '
  'the window). NULL with a NULL quantity means no evidence either way.';

COMMIT;

