const Database = require('better-sqlite3');
const path = require('path');

const DB_PATH = path.join(__dirname, 'liquor_store.db');

function createDatabase() {
  const db = new Database(DB_PATH);
  db.pragma('journal_mode = WAL');
  db.pragma('foreign_keys = ON');

  db.exec(`
    -- Stores
    CREATE TABLE IF NOT EXISTS STR (
      STORE INTEGER PRIMARY KEY,
      NAME TEXT NOT NULL,
      ADDRESS TEXT,
      CITY TEXT,
      STATE TEXT,
      PHONE TEXT
    );

    -- Categories
    CREATE TABLE IF NOT EXISTS CAT (
      CAT INTEGER PRIMARY KEY,
      NAME TEXT NOT NULL
    );

    -- Product Types
    CREATE TABLE IF NOT EXISTS TYP (
      TYPE INTEGER PRIMARY KEY,
      NAME TEXT NOT NULL,
      UPROF1 REAL DEFAULT 0, UPROF2 REAL DEFAULT 0, UPROF3 REAL DEFAULT 0, UPROF4 REAL DEFAULT 0,
      CPROF1 REAL DEFAULT 0, CPROF2 REAL DEFAULT 0, CPROF3 REAL DEFAULT 0, CPROF4 REAL DEFAULT 0,
      ML1 INTEGER DEFAULT 375, ML2 INTEGER DEFAULT 750, ML3 INTEGER DEFAULT 1000, ML4 INTEGER DEFAULT 1750
    );

    -- Sizes
    CREATE TABLE IF NOT EXISTS SIZ (
      ML INTEGER PRIMARY KEY,
      NAME TEXT NOT NULL
    );

    -- Inventory Master
    CREATE TABLE IF NOT EXISTS INV (
      SKU INTEGER PRIMARY KEY,
      SNAME TEXT NOT NULL,
      LNAME TEXT,
      CAT INTEGER REFERENCES CAT(CAT),
      TYPE INTEGER REFERENCES TYP(TYPE),
      ML INTEGER,
      ACOST REAL DEFAULT 0,
      LCOST REAL DEFAULT 0,
      PRICE REAL DEFAULT 0,
      SUPROF REAL DEFAULT 0,
      SCPROF REAL DEFAULT 0,
      MTD_DOL REAL DEFAULT 0,
      YTD_DOL REAL DEFAULT 0,
      MTD_UNITS INTEGER DEFAULT 0,
      YTD_UNITS INTEGER DEFAULT 0,
      MTD_PROF REAL DEFAULT 0,
      YTD_PROF REAL DEFAULT 0,
      WEEKS REAL DEFAULT 0
    );

    -- Stock per Store
    CREATE TABLE IF NOT EXISTS STK (
      SKU INTEGER,
      STORE INTEGER,
      FLOOR INTEGER DEFAULT 0,
      BACK INTEGER DEFAULT 0,
      SHELF INTEGER DEFAULT 0,
      RSHELF INTEGER DEFAULT 0,
      WEEKS REAL DEFAULT 0,
      SWEEKS REAL DEFAULT 4,
      SMIN INTEGER DEFAULT 2,
      SORD INTEGER DEFAULT 6,
      SHIPPED INTEGER DEFAULT 0,
      KITS INTEGER DEFAULT 0,
      SDATE TEXT,
      LVEND INTEGER DEFAULT 0,
      PVEND INTEGER DEFAULT 0,
      ACOST REAL DEFAULT 0,
      MTD_DOL REAL DEFAULT 0,
      YTD_DOL REAL DEFAULT 0,
      MTD_UNITS INTEGER DEFAULT 0,
      YTD_UNITS INTEGER DEFAULT 0,
      MTD_PROF REAL DEFAULT 0,
      YTD_PROF REAL DEFAULT 0,
      PRIMARY KEY (SKU, STORE)
    );

    -- Journal Header (transactions)
    CREATE TABLE IF NOT EXISTS JNH (
      SALE INTEGER PRIMARY KEY,
      STORE INTEGER,
      DATE TEXT,
      TSTAMP TEXT,
      TOTAL REAL DEFAULT 0,
      CASHIER INTEGER DEFAULT 0,
      REGISTER INTEGER DEFAULT 0,
      CUSTOMER INTEGER DEFAULT 0,
      TAXCODE TEXT DEFAULT 'A'
    );

    -- Journal Line (transaction items)
    CREATE TABLE IF NOT EXISTS JNL (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      SALE INTEGER REFERENCES JNH(SALE),
      SKU INTEGER,
      QTY INTEGER DEFAULT 1,
      PRICE REAL DEFAULT 0,
      COST REAL DEFAULT 0,
      CAT INTEGER DEFAULT 0,
      DISCOUNT REAL DEFAULT 0,
      DCLASS TEXT DEFAULT ''
    );

    -- History
    CREATE TABLE IF NOT EXISTS HST (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      SKU INTEGER,
      DATE TEXT,
      QTY INTEGER DEFAULT 0,
      PRICE REAL DEFAULT 0,
      COST REAL DEFAULT 0
    );

    -- Vendors
    CREATE TABLE IF NOT EXISTS VND (
      VENDOR INTEGER PRIMARY KEY,
      LASTNAME TEXT,
      FIRSTNAME TEXT,
      PHONE TEXT,
      BALANCE REAL DEFAULT 0
    );

    -- Vendor Best Price Reference
    CREATE TABLE IF NOT EXISTS VBR (
      SKU INTEGER PRIMARY KEY,
      BESTBOT1 REAL DEFAULT 0,
      BESTVEND1 INTEGER DEFAULT 0,
      BESTBOT2 REAL DEFAULT 0,
      BESTVEND2 INTEGER DEFAULT 0
    );

    -- Vendor Pricing History
    CREATE TABLE IF NOT EXISTS VPR (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      SKU INTEGER,
      VEND INTEGER,
      BESTBOT REAL DEFAULT 0,
      DATE TEXT
    );

    -- Purchase Order Header
    CREATE TABLE IF NOT EXISTS POH (
      PO INTEGER PRIMARY KEY,
      VENDOR INTEGER,
      STORE INTEGER,
      STATUS TEXT DEFAULT 'O',
      TOTAL REAL DEFAULT 0,
      ORDDATE TEXT,
      RCVDATE TEXT
    );

    -- Purchase Order Detail
    CREATE TABLE IF NOT EXISTS POD (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      PO INTEGER REFERENCES POH(PO),
      SKU INTEGER,
      OQTY INTEGER DEFAULT 0,
      COST REAL DEFAULT 0,
      PACK INTEGER DEFAULT 1,
      BQTY INTEGER DEFAULT 0,
      CREDITDUE REAL DEFAULT 0,
      CREDITPAID REAL DEFAULT 0,
      CREDITSTAT TEXT DEFAULT '',
      TRANSFER INTEGER DEFAULT 0
    );

    -- Deal Header
    CREATE TABLE IF NOT EXISTS DLH (
      DEAL INTEGER PRIMARY KEY,
      VENDOR INTEGER,
      STARTDATE TEXT,
      STOPDATE TEXT,
      QTY1 INTEGER DEFAULT 0, QTY2 INTEGER DEFAULT 0, QTY3 INTEGER DEFAULT 0,
      QTY4 INTEGER DEFAULT 0, QTY5 INTEGER DEFAULT 0,
      DESCRIPTION TEXT
    );

    -- Deal Detail
    CREATE TABLE IF NOT EXISTS DLD (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      DEAL INTEGER REFERENCES DLH(DEAL),
      SKU INTEGER,
      QTYTODATE INTEGER DEFAULT 0,
      QTYONORDER INTEGER DEFAULT 0,
      DISC1 REAL DEFAULT 0, DISC2 REAL DEFAULT 0, DISC3 REAL DEFAULT 0,
      DISC4 REAL DEFAULT 0, DISC5 REAL DEFAULT 0,
      INVOICLEVL INTEGER DEFAULT 0
    );

    -- Sale List Header (Promotions)
    CREATE TABLE IF NOT EXISTS SLH (
      SALELIST INTEGER PRIMARY KEY,
      NAME TEXT,
      STATUS TEXT DEFAULT 'A',
      START TEXT,
      STOP TEXT
    );

    -- Sale List Lines
    CREATE TABLE IF NOT EXISTS SLL (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      SALELIST INTEGER REFERENCES SLH(SALELIST),
      SKU INTEGER,
      PRICE REAL DEFAULT 0,
      COST REAL DEFAULT 0,
      PREVPRICE REAL DEFAULT 0,
      PREVQTY INTEGER DEFAULT 0,
      SALES REAL DEFAULT 0,
      PROFIT REAL DEFAULT 0,
      UNITS INTEGER DEFAULT 0,
      ONSALE INTEGER DEFAULT 1
    );

    -- Price Change Log
    CREATE TABLE IF NOT EXISTS PRCLOG (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      SKU INTEGER,
      PRICE REAL,
      OLDPRICE REAL,
      TSTAMP TEXT,
      WHO TEXT
    );

    -- Customers
    CREATE TABLE IF NOT EXISTS CUS (
      CUSTOMER INTEGER PRIMARY KEY,
      FIRSTNAME TEXT,
      LASTNAME TEXT,
      PHONE TEXT,
      BALANCE REAL DEFAULT 0,
      CRDLIMIT REAL DEFAULT 500,
      CLUBCARD TEXT DEFAULT '',
      CLUBDISC REAL DEFAULT 0,
      WSLICENSE TEXT DEFAULT '',
      WSEXPIRE TEXT DEFAULT ''
    );

    -- Customer Order Header
    CREATE TABLE IF NOT EXISTS OHD (
      ORDNUM INTEGER PRIMARY KEY,
      CUSTOMER INTEGER,
      STATUS TEXT DEFAULT 'O',
      TOTAL REAL DEFAULT 0,
      AGEDATE TEXT
    );

    -- Customer Order Detail
    CREATE TABLE IF NOT EXISTS ODD (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      ORDNUM INTEGER REFERENCES OHD(ORDNUM),
      SKU INTEGER,
      QTY INTEGER DEFAULT 1,
      PRICE REAL DEFAULT 0,
      AGEDATE TEXT
    );

    -- Bad Checks Header
    CREATE TABLE IF NOT EXISTS CHH (
      CHECKID INTEGER PRIMARY KEY,
      CUSTOMER INTEGER
    );

    -- Bad Checks Detail
    CREATE TABLE IF NOT EXISTS CHD (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      CHECKID INTEGER REFERENCES CHH(CHECKID),
      STATUS TEXT DEFAULT 'O',
      CHK_AMT REAL DEFAULT 0,
      DATE TEXT
    );

    -- Employees
    CREATE TABLE IF NOT EXISTS EMP (
      EMPID INTEGER PRIMARY KEY,
      NAME TEXT,
      ROLE TEXT DEFAULT 'Cashier'
    );

    -- Drawer Pickups
    CREATE TABLE IF NOT EXISTS PICKUP (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      REGISTER INTEGER,
      CASHIER INTEGER,
      CAT TEXT DEFAULT 'CASH',
      DESCRIPT TEXT DEFAULT '',
      AMOUNT REAL DEFAULT 0,
      PICKUP REAL DEFAULT 0,
      DATE TEXT
    );

    -- GL Accounts
    CREATE TABLE IF NOT EXISTS GLA (
      GLACCOUNT TEXT PRIMARY KEY,
      NAME TEXT,
      BALANCE REAL DEFAULT 0,
      ACCTTYPE TEXT DEFAULT 'A'
    );

    -- GL Monthly Buckets
    CREATE TABLE IF NOT EXISTS GLB (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      GLACCOUNT TEXT REFERENCES GLA(GLACCOUNT),
      DATE TEXT,
      LAMOUNT REAL DEFAULT 0,
      RAMOUNT REAL DEFAULT 0
    );

    -- Transaction Journal
    CREATE TABLE IF NOT EXISTS TRN (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      SOURCE TEXT,
      GLACCOUNT TEXT,
      LAMOUNT REAL DEFAULT 0,
      RAMOUNT REAL DEFAULT 0,
      TDATE TEXT,
      DESCRIPTION TEXT
    );

    -- Tax Codes
    CREATE TABLE IF NOT EXISTS TXC (
      CODE TEXT PRIMARY KEY,
      NAME TEXT,
      RATE REAL DEFAULT 0
    );

    -- UPC Codes
    CREATE TABLE IF NOT EXISTS UPC (
      UPC TEXT PRIMARY KEY,
      SKU INTEGER,
      LAST TEXT
    );

    -- Physical Count (Hand Count)
    CREATE TABLE IF NOT EXISTS HND (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      SKU INTEGER,
      STORE INTEGER,
      FLOOR INTEGER DEFAULT 0,
      BACK INTEGER DEFAULT 0,
      COUNTDATE TEXT
    );

    -- Kits
    CREATE TABLE IF NOT EXISTS KIT (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      SKU INTEGER,
      KSKU INTEGER,
      QTY INTEGER DEFAULT 1
    );

    -- Tax Stamps
    CREATE TABLE IF NOT EXISTS STAMPS (
      ID INTEGER PRIMARY KEY AUTOINCREMENT,
      SERIES TEXT,
      QTY INTEGER DEFAULT 0,
      SNUMBER INTEGER DEFAULT 0,
      ENUMBER INTEGER DEFAULT 0,
      DATE TEXT
    );

    -- Deposits
    CREATE TABLE IF NOT EXISTS DEP (
      SKU INTEGER PRIMARY KEY,
      UNIT REAL DEFAULT 0,
      CASEDEP REAL DEFAULT 0
    );
  `);

  return db;
}

module.exports = { createDatabase, DB_PATH };
