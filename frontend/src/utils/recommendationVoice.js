// recommendationVoice.js
// -----------------------------------------------------------------------------
// The pipeline's numbers, said in the owner's language.
//
// THE RULE THIS FILE EXISTS FOR
//   A shop owner is not a statistician and has not read the sheets. Every
//   number the pipeline produces is defensible, and almost none of it is
//   legible: `own_weight: 0.31` is a fact about our shrinkage estimator, not
//   information about their shop.
//
//   So the card speaks. "You're an emerging store - I'm using your data where
//   I can and similar shops where I can't" is a sentence somebody can act on,
//   agree with, or argue with. 0.31 is none of those things.
//
// GENERATED BY THE PIPELINE, RENDERED HERE
//   The provenance line is built in Python (sheet 15,
//   `build_provenance_sentence`) so it is checked by sheet 16 against the same
//   figures the card displays. This file RENDERS what arrives and only falls
//   back to composing one itself when the pipeline sent none - and says so, in
//   development, because a cohort-weighted card arriving without its line is a
//   pipeline bug and not a styling problem.
//
// PURE, SO IT CAN BE TESTED
//   No hooks, no React, no fetch. Every function here takes plain data and
//   returns a string or null. `null` always means "there is nothing honest to
//   say here" and the caller renders nothing - never a placeholder, never an
//   em dash standing in for a fact we do not have.
// -----------------------------------------------------------------------------

const DAYS_PER_WEEK = 7;

/**
 * NEW | EMERGING | ESTABLISHED | MATURE, said out loud.
 *
 * Deliberately first-person and deliberately about the SHOP rather than about
 * the model. The state is a statement about how much of the answer is theirs,
 * so that is what it says.
 */
const EVIDENCE_SENTENCES = {
  NEW: "You're a new store here - this is based on shops like yours, "
    + "because you don't have enough of your own history yet.",
  EMERGING: "You're an emerging store - I'm using your data where I can and "
    + "similar shops where I can't.",
  ESTABLISHED: "You're an established store - most of this comes from your "
    + 'own sales, with similar shops filling the gaps.',
  MATURE: "You're a mature store - this is your own sales history, not "
    + "anybody else's.",
};

export function evidenceSentence(evidenceState) {
  if (!evidenceState) return null;
  return EVIDENCE_SENTENCES[String(evidenceState).toUpperCase()] || null;
}

/** A short badge for the same thing, where a whole sentence will not fit. */
export function evidenceLabel(evidenceState) {
  if (!evidenceState) return null;
  const key = String(evidenceState).toUpperCase();
  if (!EVIDENCE_SENTENCES[key]) return null;
  return key.charAt(0) + key.slice(1).toLowerCase();
}

/**
 * "Based on 14 similar stores in Texas - you have 3 weeks of your own history"
 *
 * THE RUNG IS NOT THE PLACE. `cohort_level` is one of
 * store|state|region|national - the rung of the ladder that answered - and is
 * not a place name. The place, when there is one, arrives separately as
 * `cohort_region`. Printing the rung would produce "14 similar stores in
 * state", which is the bug sheet 15 hit from the other side.
 */
export function provenanceLine(provenance) {
  if (!provenance) return null;
  const weight = Number(provenance.own_weight);
  // A card built entirely on the store's own data has nothing borrowed to
  // disclose, and a hedge on a card that does not need one teaches owners to
  // ignore the hedge on cards that do.
  if (!Number.isFinite(weight) || weight >= 1) return null;

  const clauses = [];
  const size = Number(provenance.cohort_size);
  if (Number.isFinite(size) && size > 0) {
    const rung = String(provenance.cohort_level || '').toLowerCase();
    const region = provenance.cohort_region;
    // Only a geographic rung HAS a place. "national" covers everywhere and
    // naming one would be a lie even if a region is attached.
    const where = (region && (rung === 'state' || rung === 'region'))
      ? ` in ${region}` : '';
    clauses.push(`Based on ${size} similar ${size === 1 ? 'store' : 'stores'}${where}`);
  }

  const observations = Number(provenance.own_observations);
  if (Number.isFinite(observations) && observations > 0) {
    const weeks = Math.floor(observations / DAYS_PER_WEEK);
    clauses.push(weeks >= 1
      ? `you have ${weeks} ${weeks === 1 ? 'week' : 'weeks'} of your own history`
      : `you have ${observations} ${observations === 1 ? 'day' : 'days'} of your own history`);
  } else if (clauses.length) {
    // n = 0 is the pure cold-start case, and saying so is the whole point of
    // the shrinkage sheet: the card is honest that none of this is yet theirs.
    clauses.push('this is your first data on it');
  }

  if (!clauses.length) return null;
  return `${clauses.join(' - ')}.`;
}

/**
 * Does this card owe a provenance line it did not bring?
 *
 * A cohort-weighted card without one is a PIPELINE bug - sheet 15 generates
 * the line and sheet 16 checks it - so it is surfaced as a bug in development
 * rather than quietly papered over in the UI. In production the fallback in
 * `cardProvenance` composes one from the same Provenance object, because a
 * missing sentence must not become a missing disclosure in front of an owner.
 */
export function provenanceIsMissing(card) {
  const provenance = card && card.provenance;
  if (!provenance) return false;
  const weight = Number(provenance.own_weight);
  if (!Number.isFinite(weight) || weight >= 1) return false;
  return !String(card.provenance_sentence || '').trim();
}

/**
 * The line to show: the pipeline's, or one composed from the same object.
 *
 * Preferring the pipeline's matters because sheet 16 verified THAT string's
 * numerals against the validated record. A line composed here is a fallback,
 * not an equal - so it is only used when nothing arrived.
 */
export function cardProvenance(card) {
  if (!card) return null;
  const sent = String(card.provenance_sentence || '').trim();
  if (sent) return sent;
  return provenanceLine(card.provenance);
}

/**
 * "24 units (2 cases of 12)" rather than a bare 24.
 *
 * This is what makes the constraints layer read as care rather than as
 * unexplained arithmetic. A quantity that was rounded to a case pack, held
 * down by a shelf limit or lifted to a supplier minimum has a REASON, and the
 * reason is the interesting part - an owner who sees 24 wonders why not 25.
 */
export function quantityWithReason(quantity, constraints) {
  const qty = Number(quantity);
  if (!Number.isFinite(qty) || qty <= 0) return null;

  const units = `${qty} ${qty === 1 ? 'unit' : 'units'}`;
  const pack = constraints && Number(constraints.case_pack);
  if (Number.isFinite(pack) && pack > 1 && qty % pack === 0) {
    const cases = qty / pack;
    return `${units} (${cases} ${cases === 1 ? 'case' : 'cases'} of ${pack})`;
  }
  return units;
}

/**
 * Why this number and not the one the forecast asked for.
 *
 * Only rendered when the quantity was actually CHANGED. A card explaining a
 * constraint that did not bind is noise, and noise is what teaches people to
 * stop reading the explanations that matter.
 */
export function constraintNote(card) {
  if (!card) return null;
  const reasons = Array.isArray(card.constraint_reasons) ? card.constraint_reasons : [];
  if (!reasons.length) return null;
  const ideal = Number(card.ideal_qty);
  const actual = Number(card.suggested_order_qty ?? card.quantity);
  if (Number.isFinite(ideal) && Number.isFinite(actual) && Math.round(ideal) === Math.round(actual)) {
    return null;
  }
  return reasons.join('; ');
}

/**
 * Confidence in words, from the CALIBRATED value and never the raw one.
 *
 * Stated confidence was measured at 0.48 against an actual hit rate of 0.23 -
 * a coin flip with a decimal point - so the raw number is not something to put
 * in front of an owner under any label. The calibrated one has been fitted
 * against outcomes, and even then it is shown as words: "74%" invites a
 * precision nobody has earned, while "fairly confident" is the honest
 * resolution of the underlying estimate.
 */
const CONFIDENCE_BANDS = [
  [0.85, 'Very confident'],
  [0.65, 'Confident'],
  [0.45, 'Fairly confident'],
  [0.25, 'Not very confident'],
  [0.0, 'A long shot'],
];

export function confidenceWords(calibratedConfidence) {
  const value = Number(calibratedConfidence);
  if (!Number.isFinite(value)) return null;
  const band = CONFIDENCE_BANDS.find(([floor]) => value >= floor);
  return band ? band[1] : null;
}

/**
 * True when the confidence figure does NOT separate this card from the others.
 *
 * Two ways the server says so. The live card carries the boolean; the stored
 * card carries only `confidence_basis`, where the engine appends a suffix for
 * exactly this case - `_flat_slate` when every card in the finished slate
 * scored the same, `_constant` when the curve itself has one level and can
 * only ever return one number.
 */
function confidenceIsFlat(card) {
  if (card.confidence_discriminates === false) return true;
  const basis = card.confidence_basis;
  return typeof basis === 'string'
    && (basis.endsWith('_flat_slate') || basis.endsWith('_constant'));
}

/**
 * The confidence to display, insisting on the calibrated field.
 *
 * Returns null rather than falling back to a raw `confidence` value. An
 * uncalibrated number shown under a confidence label is worse than no label:
 * it is the 0.48-against-0.23 problem wearing the word that makes people trust
 * it. A card with no calibrated confidence simply does not claim one.
 *
 * AND NULL WHEN THE FIGURE DOES NOT DISCRIMINATE. The band is read as a
 * statement about THIS card - "Fairly confident" next to one recommendation and
 * not the next one means something. When every card in the slate carries the
 * same number, the band says the same word on all of them and the reader
 * reasonably concludes the engine ranked them that way. It did not: Bethany's
 * curve mapped every raw score from 0.161 to 0.515 onto 0.444, so nine cards
 * wore one word that distinguished none of them.
 *
 * The value is not wrong and is not discarded - the server keeps it and
 * explains it as a store-level rate in `confidence_explain`. What is withheld
 * is the per-card CLAIM, which is the thing that was never true.
 */
export function cardConfidence(card) {
  if (!card) return null;
  const calibrated = card.calibrated_confidence;
  if (calibrated === undefined || calibrated === null) return null;
  if (confidenceIsFlat(card)) return null;
  return confidenceWords(calibrated);
}

/**
 * The store-level sentence to show in place of a withheld band, or null.
 *
 * Only when the figure exists but does not discriminate: that is the case
 * where the reader would otherwise just see a gap and wonder what happened.
 */
export function confidenceNote(card) {
  if (!card) return null;
  const calibrated = card.calibrated_confidence;
  if (calibrated === undefined || calibrated === null) return null;
  if (!confidenceIsFlat(card)) return null;
  return card.confidence_explain || null;
}

/** True when a card may be shown to a STORE. The server decides; this agrees. */
export function isLive(card) {
  return !card || !card.gate_state ? true : card.gate_state === 'live';
}

const recommendationVoice = {
  cardConfidence,
  confidenceNote,
  cardProvenance,
  confidenceWords,
  constraintNote,
  evidenceLabel,
  evidenceSentence,
  isLive,
  provenanceIsMissing,
  provenanceLine,
  quantityWithReason,
};

export default recommendationVoice;
